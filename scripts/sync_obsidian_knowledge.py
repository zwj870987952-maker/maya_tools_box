def text_file(path):
    return path.read_text(encoding="utf-8-sig", errors="replace")


def parse_python(path):
    try:
        return ast.parse(text_file(path), filename=str(path))
    except (SyntaxError, OSError, UnicodeError):
        return None


def static_value(node):
    try:
        return ast.literal_eval(node)
    except (ValueError, TypeError, SyntaxError, MemoryError):
        if isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name):
            if node.value.id == "ToolDomain":
                return node.attr.lower()
    return None


def class_attributes(node):
    values = {}
    for statement in node.body:
        if isinstance(statement, ast.Assign):
            for target in statement.targets:
                if isinstance(target, ast.Name):
                    values[target.id] = static_value(statement.value)
        elif isinstance(statement, ast.AnnAssign) and isinstance(statement.target, ast.Name):
            values[statement.target.id] = static_value(statement.value)
    return values


def registered_classes():
    tree = parse_python(ROOT / "maya_toolkit" / "tools" / "__init__.py")
    if tree is None:
        return set()
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == "ALL_TOOL_CLASSES"
            for target in node.targets
        ):
            if isinstance(node.value, (ast.List, ast.Tuple)):
                return {item.id for item in node.value.elts if isinstance(item, ast.Name)}
    return set()


def package_exports(package):
    tree = parse_python(ROOT / "maya_toolkit" / package / "__init__.py")
    exports = {}
    if tree is not None:
        for node in tree.body:
            if isinstance(node, ast.ImportFrom) and node.level == 1 and node.module:
                for alias in node.names:
                    exports[alias.asname or alias.name] = node.module
    return exports


def code_files(directory):
    files = []
    if not directory.exists():
        return files
    for path in directory.rglob("*"):
        if path.is_file() and path.suffix.lower() in CODE_SUFFIXES:
            if not any(part in IGNORED_DIRS for part in path.relative_to(directory).parts):
                files.append(path)
    return sorted(files)


def code_size(paths):
    return sum(path.stat().st_size for path in paths)


def module_dependencies(files, exports, package):
    result = set()
    for path in files:
        if path.suffix.lower() != ".py":
            continue
        tree = parse_python(path)
        if tree is None:
            continue
        for node in ast.walk(tree):
            if not isinstance(node, ast.ImportFrom):
                continue
            parts = (node.module or "").split(".")
            if package not in parts:
                continue
            index = parts.index(package)
            if index + 1 < len(parts):
                module = parts[index + 1]
                if (ROOT / "maya_toolkit" / package / (module + ".py")).exists():
                    result.add(module)
            else:
                for alias in node.names:
                    module = exports.get(alias.name)
                    if module and (ROOT / "maya_toolkit" / package / (module + ".py")).exists():
                        result.add(module)
    return sorted(result)


def production_tools():
    registered = registered_classes()
    core_exports = package_exports("core")
    framework_exports = package_exports("framework")
    result = []
    base = ROOT / "maya_toolkit" / "tools"
    for tool_path in sorted(base.glob("*/tool.py")):
        tree = parse_python(tool_path)
        if tree is None:
            continue
        for node in tree.body:
            if not isinstance(node, ast.ClassDef):
                continue
            if not any(isinstance(base, ast.Name) and base.id == "BaseMayaTool"
                       or isinstance(base, ast.Attribute) and base.attr == "BaseMayaTool"
                       for base in node.bases):
                continue
            values = class_attributes(node)
            tool_id = values.get("tool_id")
            if not isinstance(tool_id, str) or not tool_id:
                continue
            sources = code_files(tool_path.parent)
            result.append({
                "tool_id": tool_id,
                "name": values.get("tool_name") or tool_id,
                "domain": values.get("category") or "other",
                "version": values.get("version") or "unknown",
                "description": values.get("description") or "",
                "schema": values.get("parameters_schema") or {},
                "class_name": node.name,
                "registered": node.name in registered,
                "source": tool_path,
                "source_files": sources,
                "core_dependencies": module_dependencies(sources, core_exports, "core"),
                "framework_dependencies": module_dependencies(sources, framework_exports, "framework"),
            })
    return sorted(result, key=lambda item: item["tool_id"])


def staging_inventory():
    path = ROOT / "tools_staging_pool" / "README.md"
    items = {}
    if not path.exists():
        return items
    pattern = re.compile(
        r"^\|\s*(\d+)\s*\|\s*([^|]+)\|\s*\*\*(.*?)\*\*\s*\|"
        r"\s*\[[^\]]+\]\((<[^>]+>|[^)]+)\)\s*\|\s*(.*?)\s*\|\s*$"
    )
    for line in text_file(path).splitlines():
        match = pattern.match(line)
        if not match:
            continue
        main_source = match.group(4).strip("<>").replace("\\", "/")
        parts = Path(main_source).parts
        if len(parts) < 2:
            continue
        key = "/".join(parts[:2])
        items[key] = {
            "name": match.group(3).strip(),
            "description": match.group(5).strip(),
            "main_source": main_source,
        }
    return items


def staging_tools():
    inventory = staging_inventory()
    result = []
    base = ROOT / "tools_staging_pool"
    for category in sorted(base.iterdir()):
        if not category.is_dir() or not re.match(r"^\d\d_", category.name):
            continue
        for directory in sorted(category.iterdir()):
            if not directory.is_dir() or directory.name in IGNORED_DIRS:
                continue
            key = category.name + "/" + directory.name
            item = inventory.get(key, {})
            sources = code_files(directory)
            main_source = base / item["main_source"] if item.get("main_source") else None
            if main_source is not None and not main_source.is_file():
                main_source = None
            if main_source is None and sources:
                main_source = sources[0]
            result.append({
                "key": key,
                "slug": category.name + "--" + directory.name,
                "category": category.name,
                "name": item.get("name") or directory.name,
                "description": item.get("description") or "待补充功能说明。",
                "indexed": key in inventory,
                "directory": directory,
                "main_source": main_source,
                "source_files": sources,
            })
    return result, inventory


def module_notes():
    result = []
    for layer in ("core", "framework", "ui"):
        for path in sorted((ROOT / "maya_toolkit" / layer).glob("*.py")):
            if path.name == "__init__.py":
                continue
            tree = parse_python(path)
            symbols = []
            if tree is not None:
                symbols = [
                    node.name for node in tree.body
                    if isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef))
                    and not node.name.startswith("_")
                ]
            result.append({
                "layer": layer,
                "name": path.stem,
                "path": path,
                "symbols": symbols,
            })
    return result


def verified_workflows(production):
    path = KNOWLEDGE / "relations.json"
    if not path.exists():
        return []
    try:
        payload = json.loads(text_file(path))
    except (ValueError, OSError) as exc:
        raise ValueError("无法读取 knowledge/relations.json: {}".format(exc))
    if not isinstance(payload, dict) or not isinstance(payload.get("verified_workflows"), list):
        raise ValueError("knowledge/relations.json 必须包含 verified_workflows 数组")
    tool_ids = {tool["tool_id"] for tool in production if tool["registered"]}
    result = []
    for item in payload.get("verified_workflows", []):
        if not isinstance(item, dict):
            continue
        source = item.get("from")
        target = item.get("to")
        if source not in tool_ids or target not in tool_ids or source == target:
            continue
        result.append({
            "from": source,
            "to": target,
            "reason": str(item.get("reason", "")),
            "evidence": str(item.get("evidence", "")),
        })
    return result


def yaml_string(value):
    return json.dumps(str(value), ensure_ascii=False)


def header(kind, **properties):
    lines = ["---", "type: " + yaml_string(kind)]
    for key, value in properties.items():
        if isinstance(value, bool):
            lines.append("{}: {}".format(key, str(value).lower()))
        elif isinstance(value, (int, float)):
            lines.append("{}: {}".format(key, value))
        else:
            lines.append("{}: {}".format(key, yaml_string(value)))
    lines.append("---")
    return "\n".join(lines)


def wiki(relative, label):
    target = "knowledge/_generated/" + (relative[:-3] if relative.endswith(".md") else relative)
    return "[[{}|{}]]".format(target, str(label).replace("|", "／").replace("]", "）"))


def source_link(note_relative, source):
    target = os.path.relpath(source, start=(GENERATED / note_relative).parent).replace("\\", "/")
    return "[查看源码]({})".format(quote(target, safe="/-._~"))


def table_text(value):
    return str(value).replace("|", "／").replace("\n", " ")


