def sync():
    production = production_tools()
    staging, inventory = staging_tools()
    modules = module_notes()
    workflows = verified_workflows(production)
    expected = {}

    for tool in production:
        expected["正式工具/{}.md".format(tool["tool_id"])] = render_production(tool, workflows)
    for tool in staging:
        expected["待整理/{}.md".format(tool["slug"])] = render_staging(tool)
    for module in modules:
        users = [
            tool for tool in production
            if module["layer"] in ("core", "framework")
            and module["name"] in tool[module["layer"] + "_dependencies"]
        ]
        expected["代码模块/{}--{}.md".format(module["layer"], module["name"])] = render_module(module, users)
    for domain, name in DOMAIN_NAMES.items():
        tools = [tool for tool in production if tool["domain"] == domain]
        lines = [header("domain", domain=domain), "# " + name, "", "## 正式工具", ""]
        lines.extend("- " + wiki("正式工具/{}.md".format(tool["tool_id"]), tool["name"]) for tool in tools)
        if not tools:
            lines.append("暂无已转正工具。")
        expected["领域/{}.md".format(domain)] = "\n".join(lines) + "\n"
    for category in sorted({tool["category"] for tool in staging}):
        tools = [tool for tool in staging if tool["category"] == category]
        lines = [header("staging-category", category=category), "# " + category, "", "## 待整理工具", ""]
        lines.extend("- " + wiki("待整理/{}.md".format(tool["slug"]), tool["name"]) for tool in tools)
        expected["待整理分类/{}.md".format(category)] = "\n".join(lines) + "\n"

    expected["规模评估.md"] = render_dashboard(production, staging, inventory, modules, workflows)
    expected["能力关联.md"] = render_relations(production, workflows)
    expected["项目地图.md"] = render_map(production)
    expected["总览.md"] = "\n".join([
        header("knowledge-home"),
        "# Maya Tools Box 知识库",
        "",
        "- " + wiki("规模评估.md", "项目规模与能力总览"),
        "- " + wiki("能力关联.md", "工具与公共代码关联"),
        "- " + wiki("项目地图.md", "项目结构图"),
        "",
        "## 项目规范",
        "",
        "- [[README|项目说明]]",
        "- [[AGENTS|代理开发规则]]",
        "- [[DEVELOPMENT_SPEC|工具转正规范]]",
        "- [[docs/llm_tools_cheatsheet|API 速查]]",
        "",
        "生成页以代码和目录为准。任何工具的实际效果与跨工具组合仍需 Maya 直验。",
        "",
    ])

    changed = 0
    expected_paths = set()
    for relative, body in expected.items():
        path = GENERATED / relative
        expected_paths.add(path)
        body = body.rstrip() + "\n"
        frontmatter_end = body.find("\n---\n", 4)
        if frontmatter_end < 0:
            raise ValueError("Generated page lacks YAML frontmatter: {}".format(relative))
        insert_at = frontmatter_end + len("\n---\n")
        content = body[:insert_at] + "\n" + MARKER + "\n" + body[insert_at:]
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or text_file(path) != content:
            path.write_text(content, encoding="utf-8")
            changed += 1
    if GENERATED.exists():
        for path in GENERATED.rglob("*.md"):
            if path not in expected_paths and MARKER in text_file(path)[:512]:
                path.unlink()
                changed += 1
    return {
        "production": len(production),
        "registered": sum(tool["registered"] for tool in production),
        "staging": len(staging),
        "inventory": len(inventory),
        "pages": len(expected),
        "changed": changed,
    }


def watched_files():
    paths = [ROOT / name for name in ("README.md", "AGENTS.md", "DEVELOPMENT_SPEC.md",
                                     "knowledge/relations.json")]
    for folder in ("maya_toolkit", "tools_staging_pool", "docs", "tests"):
        base = ROOT / folder
        if not base.exists():
            continue
        for path in base.rglob("*"):
            if path.is_file() and path.suffix.lower() in WATCH_SUFFIXES:
                if not any(part in IGNORED_DIRS for part in path.relative_to(base).parts):
                    paths.append(path)
    return sorted(set(path for path in paths if path.exists()))


def snapshot():
    return tuple((str(path.relative_to(ROOT)), path.stat().st_mtime_ns, path.stat().st_size)
                 for path in watched_files())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--watch", action="store_true", help="Regenerate after source file changes")
    parser.add_argument("--interval", type=float, default=2.0, help="Watch polling interval in seconds")
    args = parser.parse_args()
    last = None
    while True:
        current = snapshot()
        if current != last:
            try:
                report = sync()
                print(json.dumps(report, ensure_ascii=False), flush=True)
            except Exception as exc:
                if not args.watch:
                    raise
                print("知识库同步失败: {}".format(exc), file=sys.stderr, flush=True)
            last = snapshot()
        if not args.watch:
            break
        try:
            time.sleep(max(args.interval, 0.5))
        except KeyboardInterrupt:
            break


if __name__ == "__main__":
    main()
