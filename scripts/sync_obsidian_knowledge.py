def render_relations(production, workflows):
    pairs = []
    for index, left in enumerate(production):
        if not left["registered"]:
            continue
        for right in production[index + 1:]:
            if not right["registered"]:
                continue
            shared = sorted(set(left["core_dependencies"]) & set(right["core_dependencies"]))
            if shared:
                pairs.append((left, right, shared))
    lines = [
        header("structural-relations"),
        "# 工具与公共代码关联",
        "",
        "> 下表来自 Python import 的静态分析，只表示共享底层代码；不是经过验证的功能调用链。",
        "",
        "| 工具 A | 工具 B | 共同引用的 core 模块 |",
        "| --- | --- | --- |",
    ]
    for left, right, shared in sorted(pairs, key=lambda item: (-len(item[2]), item[0]["tool_id"], item[1]["tool_id"])):
        lines.append("| {} | {} | {} |".format(
            wiki("正式工具/{}.md".format(left["tool_id"]), left["tool_id"]),
            wiki("正式工具/{}.md".format(right["tool_id"]), right["tool_id"]),
            "、".join(wiki("代码模块/core--{}.md".format(name), name) for name in shared)))
    if not pairs:
        lines.append("| — | — | 尚无共同引用 |")
    lines += [
        "",
        "## 已确认的功能组合",
        "",
    ]
    if workflows:
        lines += [
            "| 前置工具 | 后续工具 | 组合理由 | 验证说明 |",
            "| --- | --- | --- | --- |",
        ]
        for item in workflows:
            evidence = item["evidence"]
            evidence_link = "[说明]({})".format(quote(os.path.relpath(
                ROOT / evidence, start=GENERATED).replace("\\", "/"), safe="/-._~")) if evidence and (ROOT / evidence).is_file() else "—"
            lines.append("| {} | {} | {} | {} |".format(
                wiki("正式工具/{}.md".format(item["from"]), item["from"]),
                wiki("正式工具/{}.md".format(item["to"]), item["to"]),
                table_text(item["reason"]), evidence_link))
    else:
        lines.append("目前没有经 Maya 直验并登记的跨工具调用链。后续可按 [知识卡模板](../../docs/tools/_tool_knowledge_template.md) 补充输入输出衔接，再把已确认关系写入 knowledge/relations.json。")
    lines.append("")
    return "\n".join(lines)


